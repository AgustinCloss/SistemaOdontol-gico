    private void guardarlabelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_guardarlabelMouseClicked
                
        String selectedItemSexo = (String) sexocombo.getSelectedItem();
        Date selectedDate = FechaChooser.getDate();
        String apellidotext = apellidotxt.getText();
        String nombretext = nombretxt.getText();
        String documentotext = documentotxt.getText();
        
        if((selectedDate == null) || ("Sexo*".equals(selectedItemSexo))  ) 
        {
              JOptionPane.showMessageDialog(this, 
                        "Por favor, rellene todos los campos obligatorios.", 
                        "Error de Validación", 
                        JOptionPane.ERROR_MESSAGE);} 
        else if(("Apellido*".equals(apellidotext)) || ("Nombre*".equals(nombretext)) || ("Nº de Documento*".equals(documentotext)))
        {
            JOptionPane.showMessageDialog(this, 
                        "Por favor, rellene todos los campos obligatorios.", 
                        "Error de Validación", 
                        JOptionPane.ERROR_MESSAGE);
        }
        
        else if(("".equals(apellidotext)) || ("".equals(nombretext)) || ("".equals(documentotext)))
        {
            JOptionPane.showMessageDialog(this, 
                        "Por favor, rellene todos los campos obligatorios.", 
                        "Error de Validación", 
                        JOptionPane.ERROR_MESSAGE);
        }  else {
            
        JOptionPane.showMessageDialog(this, 
                        "Datos guardados correctamente.", 
                        "Éxito", 
                        JOptionPane.INFORMATION_MESSAGE);
        
        this.dispose();
        }


    }//GEN-LAST:event_guardarlabelMouseClicked

