    private void quitarlabelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_quitarlabelMouseClicked
        Object[] options = {"Sí", "No"};
        
        // Mostrar el diálogo con botones personalizados
        int response = JOptionPane.showOptionDialog(this,
                "¿Está seguro de que quiere quitar el turno?",
                "Quitar Turno",
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null, // Icono nulo
                options, // Opciones personalizadas
                options[1]); // Opción por defecto
        
         if (response == 0) { // "Sí" (opción 0)
             
           JOptionPane.showMessageDialog(null, "Turno quitado con éxito", "Quitar Turno", JOptionPane.INFORMATION_MESSAGE);
        
        
        } 
    }//GEN-LAST:event_quitarlabelMouseClicked

