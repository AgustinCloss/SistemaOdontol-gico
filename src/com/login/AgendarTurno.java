    private void guardarlabelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_guardarlabelMouseClicked
        String dnitext = dnitxt.getText();
        String nombretext = nombretxt.getText();
        Date selectedDate = fechachooser.getDate();
        String selectedItemMotivo = (String) motivocombo.getSelectedItem();
        
        
        if((selectedDate == null) || ("Seleccione motivo de consulta*".equals(selectedItemMotivo))  ) 
        {
              JOptionPane.showMessageDialog(this, 
                        "Por favor, rellene todos los campos obligatorios.", 
                        "Error de Validación", 
                        JOptionPane.ERROR_MESSAGE);} 
        else if((horacombo.getSelectedIndex() == -1) || (duracombo.getSelectedIndex() == -1) || (estadocombo.getSelectedIndex() == -1))
        {
            JOptionPane.showMessageDialog(this, 
                        "Por favor, rellene todos los campos obligatorios.", 
                        "Error de Validación", 
                        JOptionPane.ERROR_MESSAGE);
        }
        
        else if(("".equals(dnitext)) || ("".equals(nombretext)))
        {
            JOptionPane.showMessageDialog(this, 
                        "Por favor, rellene todos los campos obligatorios.", 
                        "Error de Validación", 
                        JOptionPane.ERROR_MESSAGE);
        }
            
            else if(("DNI*".equals(dnitext)) || ("Nombre completo*".equals(nombretext)))
        {
            JOptionPane.showMessageDialog(this, 
                        "Por favor, rellene todos los campos obligatorios.", 
                        "Error de Validación", 
                        JOptionPane.ERROR_MESSAGE);
        }
          else {
            
        JOptionPane.showMessageDialog(this, 
                        "Datos guardados correctamente.", 
                        "Éxito", 
                        JOptionPane.INFORMATION_MESSAGE);
        
        Agenda ag = new Agenda();
            
            ag.setVisible(true);
            ag.setLocationRelativeTo(null);
            this.setVisible(false);
        }
    }//GEN-LAST:event_guardarlabelMouseClicked

