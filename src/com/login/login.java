    private void nombreusuariotxtMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_nombreusuariotxtMousePressed
        
        if(nombreusuariotxt.getText().equals("Ingrese el nombre de usuario")){
            
           nombreusuariotxt.setText("");
           nombreusuariotxt.setForeground(Color.black);
           
        }
        
        if(String.valueOf(contraseñatxt.getPassword()).isEmpty()){
            
           contraseñatxt.setText("********");
           contraseñatxt.setForeground(Color.gray);
           
        
        }
    }//GEN-LAST:event_nombreusuariotxtMousePressed

    private void contraseñatxtMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_contraseñatxtMousePressed
        
        if(nombreusuariotxt.getText().isEmpty()){
            
           nombreusuariotxt.setText("Ingrese el nombre de usuario");
           nombreusuariotxt.setForeground(Color.gray);
           
        }
        if(String.valueOf(contraseñatxt.getPassword()).equals("********")){
            
        contraseñatxt.setText("");
        contraseñatxt.setForeground(Color.black);
        
        }
    }//GEN-LAST:event_contraseñatxtMousePressed

    private void ingresarlabelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_ingresarlabelMouseClicked
        
        if((String.valueOf(contraseñatxt.getPassword()).equals("admin")) && (nombreusuariotxt.getText().equals("admin"))) {
        
            MenuPrincipal menu = new MenuPrincipal();
            
            menu.setVisible(true);
            menu.setLocationRelativeTo(null);
            this.setVisible(false);
            
        }
    }//GEN-LAST:event_ingresarlabelMouseClicked

