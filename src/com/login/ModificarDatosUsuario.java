    private void guardarlabelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_guardarlabelMouseClicked
         String regex = "^(?=.*[0-9])(?=.*[a-z])(?=.*[A-Z])(?=.*[@#$%^&+=]).{8,}$";
        Pattern pattern = Pattern.compile(regex);
        Matcher matcher = pattern.matcher(contraseñatxt.getText());
        
        if(nombreusuariotxt.getText().equals("")) {
         JOptionPane.showMessageDialog(null, "No ha ingresado un nombre de usuario", "Error de Validación", JOptionPane.ERROR_MESSAGE);
         }
        
        else if(matcher.matches() == false)
        {
            JOptionPane.showMessageDialog(null, "La contraseña no es válida. Debe tener al menos 8 caracteres, incluir un número, una letra minúscula, una letra mayúscula y un carácter especial.", "Error de Validación", JOptionPane.ERROR_MESSAGE);}
        else if(!contraseñatxt.getText().equals(repitatxt.getText())) {
            
            JOptionPane.showMessageDialog(null, "Las contraseñas no coinciden.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
        }
        
        else{
        JOptionPane.showMessageDialog(null, "Cambios guardados con éxito", "Modificar Datos de Usuario", JOptionPane.INFORMATION_MESSAGE);
        
         MenuPrincipal m = new MenuPrincipal();
            
            m.setVisible(true);
            m.setLocationRelativeTo(null);
            this.setVisible(false);}
    }//GEN-LAST:event_guardarlabelMouseClicked

