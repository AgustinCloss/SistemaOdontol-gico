    private void bajaiconoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_bajaiconoMouseClicked
        
       Object[] options = {"Sí", "No"};
        
        // Mostrar el diálogo con botones personalizados
        int response = JOptionPane.showOptionDialog(this,
                "¿Está seguro de que quiere dar de baja su cuenta?",
                "Dar de baja cuenta",
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null, // Icono nulo
                options, // Opciones personalizadas
                options[1]); // Opción por defecto
        
         if (response == 0) { // "Sí" (opción 0)
             
            VerificarContraseña ver = new VerificarContraseña();
            
            ver.setVisible(true);
            ver.setLocationRelativeTo(null);
            this.setVisible(false);
            
        } 
        
        
    }//GEN-LAST:event_bajaiconoMouseClicked

